"""Write re/PARITY.md: our indicators and bars vs TradingView's own output (needs the sidecar).

Run from server/: python scripts/parity_report.py
"""
import sys
import time
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tvre import bars, indicators  # noqa: E402
from tvre.providers import local, tradingview  # noqa: E402
from tvre.providers.tradingview import SidecarError  # noqa: E402
from tvre.symbols import to_local  # noqa: E402

SYMBOLS = [("SSE:510300", "D"), ("NASDAQ:AAPL", "D"), ("BINANCE:BTCUSDT", "60")]
WARMUP = 300   # recursive (EMA/RMA) outputs converge to TradingView's longer-history values by then


def indicator_rows():
    rows = []
    for symbol, tf in SYMBOLS:
        for kind, spec in indicators.REGISTRY.items():
            if not spec.tv_builtin:
                continue
            try:
                tv = tradingview.indicator(symbol, tf, spec.tv_builtin, 400)
            except SidecarError as e:
                rows.append((symbol, tf, kind, "—", "—", f"refused: {e.code} ({str(e)[:60]})"))
                continue
            frame = pd.DataFrame(tv["candles"], columns=bars.COLUMNS)
            ours = indicators.compute(kind, frame)
            by_t = {r["$time"]: r for r in tv["values"]}
            for key, plot in spec.tv_plot.items():
                ref = np.array([by_t.get(t, {}).get(plot, np.nan) if by_t.get(t, {}).get(plot) is not None else np.nan
                                for t in frame.time], dtype="float64")
                mine = np.asarray(ours[key], dtype="float64")
                what = "levels"
                if spec.cumulative:
                    ref, mine, what = np.diff(ref, prepend=np.nan), np.diff(mine, prepend=np.nan), "increments"
                ok = np.isfinite(ref) & np.isfinite(mine)
                ok[:WARMUP] = False
                errs = np.abs(mine[ok] - ref[ok]) / np.maximum(np.abs(ref[ok]), 1.0 if spec.cumulative else 1e-9)
                verdict = ("✅ match" if errs.max() < 1e-6 else "❌ differs") if errs.size else "no overlap"
                rows.append((symbol, tf, f"{kind}.{key} ({what})", int(ok.sum()), f"{errs.max():.1e}" if errs.size else "—", verdict))
            time.sleep(0.5)
    return rows


def bar_rows():
    out = []
    d = tradingview.get_bars("SSE:510300", "D", 800)
    for tf in ("W", "M"):
        tvb = tradingview.get_bars("SSE:510300", tf, 40)
        m = tvb.merge(bars.resample(d, tf), on="time", suffixes=("_tv", "_us")).iloc[1:-1]
        err = float((m.close_tv - m.close_us).abs().max()) if len(m) else float("nan")
        out.append((f"SSE:510300 {tf}: TradingView vs our resample of TV daily", len(m), f"max |Δclose| = {err:.2e}"))
    tv = tradingview.get_bars("SSE:510300", "D", 2000)
    lo = local.get_bars(to_local("SSE:510300"), "D", 2000)
    m = tv.merge(lo, on="time", suffixes=("_tv", "_lo"))
    diff = (m.close_tv - m.close_lo)
    seg = diff.rolling(5, center=True, min_periods=1).median()
    steps = int((seg.diff().abs() > 0.005).sum())
    out.append(("SSE:510300 D: TradingView (raw) − local panel (前复权)", len(m),
                f"piecewise-constant offset, {steps} dividend steps, now {diff.iloc[-1]:.3f}; volume ratio "
                f"{float((m.volume_tv / m.volume_lo).median()):.3f}"))
    return out


def main():
    ind = indicator_rows()
    br = bar_rows()
    lines = [f"# Parity report — {date.today()}", "",
             "Generated by `server/scripts/parity_report.py` against the live TradingView feed (anonymous session).",
             f"Indicator values are compared on the identical candles TradingView returned with the study, after a {WARMUP}-bar warm-up.",
             "TypeScript ports are checked against the Python reference separately (`web/test/indicators.test.ts`, 1e-9).", "",
             "## Indicators vs TradingView built-in studies", "",
             "| Symbol | TF | Output | n | max rel err | Verdict |", "|---|---|---|---|---|---|"]
    lines += [f"| {' | '.join(str(x) for x in r)} |" for r in ind]
    lines += ["", "Refused studies need a TradingView account: export `TV_SESSIONID` / `TV_SESSIONID_SIGN` before starting the sidecar and rerun.", "",
              "## Bars", "", "| Check | n | Result |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in br]
    dest = Path(__file__).resolve().parents[2] / "re" / "PARITY.md"
    dest.write_text("\n".join(lines) + "\n")
    print(dest.read_text())


if __name__ == "__main__":
    main()
